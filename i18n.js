export const resolveInterfaceLanguage = (saved, browserLanguage = 'en') =>
  saved === 'zh' || saved === 'en' ? saved : /^zh(?:[-_]|$)/i.test(browserLanguage) ? 'zh' : 'en';

export const translate = (language, key, values = {}) => {
  const message = messages[language]?.[key] ?? messages.en[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
};
